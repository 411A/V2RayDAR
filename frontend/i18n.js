/* V2RayDAR dashboard strings — the single home of every user-facing text.
 *
 * LANGUAGES: `en` (default), `fa`, `zh`, `fr`, `ru` — keyed by locale code.
 * HOW TO ADD A LANGUAGE:
 *   1. Copy the whole `en` table to a new key, translate values.
 *   2. Keep every key and every `{placeholder}` name identical.
 *   3. Map the menu code to the locale in app.js `LANG_LOCALE`.
 *
 * RULES:
 * - app.js never hardcodes user text; it calls `t("key")` or `t("key", vars).
 * - index.html never hardcodes user text either; it carries `data-i18n="key"`
  *   (textContent), `data-i18n-ph` (placeholder), `data-i18n-aria` (aria-label),
  *   `data-i18n-title` (title), `data-i18n-alt` (alt), `data-i18n-content`
  *   (meta content), `data-i18n-href` (link destination) — applied by
  *   `applyI18nStatic()` at boot.
 * - Symbols ("—", "×", "…", units like "ms"/"KB") stay inline in app.js: they
 *   are not words and do not translate.
 * - Server-provided content (setting guides, fetch-error lines, log lines,
 *   config names) is NOT in this file — the backend owns those bytes.
 * - RTL: `setDocLang` mirrors the page direction (`fa` → rtl); `t()` wraps
 *   every substituted value in U+2068 FSI … U+2069 PDI isolates so Latin
 *   numbers/URLs inside RTL sentences keep their place. FSI (not LRI):
 *   a nested already-localized phrase (e.g. "{m} دقیقه پیش") takes its
 *   direction from its own first strong character instead of being forced
 *   left-to-right, which would push a leading number to the wrong end.
 */

