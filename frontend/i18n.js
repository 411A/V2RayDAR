let i18nLang = "en";

function i18nTable() {
  return I18N_STRINGS[i18nLang] || I18N_STRINGS.en;
}

/// Translate `key`, filling `{placeholders}` from `vars`. Unknown keys fall
/// back to the key itself (never blank) — the key-coverage test fails the
/// build long before that fallback can reach a user.
function t(key, vars) {
  const table = i18nTable();
  let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      // Bidi-isolate every substituted value (U+2068 FSI / U+2069 PDI):
      // without this a Latin number/URL inside an RTL sentence jumps to the
      // wrong end ("3 ..." renders as "... 3"). FSI — not LRI — because a
      // value can itself be an already-localized phrase ("2 دقیقه پیش"):
      // forced-LTR would scramble its word order, while FSI takes the
      // direction from the value's first strong character (RTL here) and
      // falls back to the surrounding paragraph for bare numbers/URLs.
      // Empty values stay empty.
      const v = String(vars[k]);
      s = s.split("{" + k + "}").join(v === "" ? "" : "\u2068" + v + "\u2069");
    }
  }
  return s;
}

/// True when `key` has a translation in the active locale (used for dynamic
/// keys like `setName_<setting>` that the key-coverage test cannot see).
function thas(key) {
  return Object.prototype.hasOwnProperty.call(i18nTable(), key);
}

/// Page direction per locale (Persian reads right-to-left).
function docDir(lang) {
  return lang === "fa" ? "rtl" : "ltr";
}

/// `<html lang>` + `<html dir>` mirror (null-safe: the node unit sandbox has
/// no `documentElement`, and the attributes are cosmetic there anyway).
function setDocLang(lang) {
  try {
    if (document.documentElement) {
      document.documentElement.lang = lang;
      document.documentElement.dir = docDir(lang);
    }
  } catch (err) {
    /* ignore */
  }
}

function setLanguage(lang) {
  if (!I18N_STRINGS[lang]) {
    return false;
  }
  i18nLang = lang;
  try {
    window.localStorage.setItem(I18N_LANG_KEY, lang);
  } catch (err) {
    /* private mode etc. — language still applies for the session */
  }
  setDocLang(lang);
  applyI18nStatic(document);
  return true;
}

function loadLanguage() {
  let saved = "en";
  try {
    const v = window.localStorage.getItem(I18N_LANG_KEY);
    if (v && I18N_STRINGS[v]) {
      saved = v;
    }
  } catch (err) {
    saved = "en";
  }
  i18nLang = saved;
  setDocLang(saved);
}

/// Apply every `data-i18n*` binding in index.html (static shell text only —
/// dynamic renders call `t()` directly).
function applyI18nStatic(root) {
  if (!root || !root.querySelectorAll) {
    return;
  }
  const set = (attr, fn) => {
    const nodes = root.querySelectorAll("[" + attr + "]");
    for (let i = 0; i < nodes.length; i += 1) {
      fn(nodes[i], nodes[i].getAttribute(attr));
    }
  };
  set("data-i18n", (n, k) => {
    n.textContent = t(k);
  });
  set("data-i18n-ph", (n, k) => {
    n.setAttribute("placeholder", t(k));
  });
  set("data-i18n-aria", (n, k) => {
    n.setAttribute("aria-label", t(k));
  });
  set("data-i18n-title", (n, k) => {
    n.title = t(k);
  });
  set("data-i18n-alt", (n, k) => {
    n.setAttribute("alt", t(k));
  });
  set("data-i18n-content", (n, k) => {
    n.setAttribute("content", t(k));
  });
  // Localized destinations (the keys-dialog support link points at the
  // help page matching the active language).
  set("data-i18n-href", (n, k) => {
    n.setAttribute("href", t(k));
  });
}
